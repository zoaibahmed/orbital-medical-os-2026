import { test, expect } from './fixtures'
test('benchmark has a deliberate reversible camera move and one renderer', async ({ page }) => {
  await page.goto('/visual-benchmark')
  await expect(page.getByTestId('benchmark-status')).toHaveAttribute('data-state','ready',{timeout:90000})
  await expect(page.locator('canvas')).toHaveAttribute('data-camera-transition','settled')
  const renderer=await page.locator('canvas').getAttribute('data-renderer-instance')
  const overview=await page.locator('canvas').getAttribute('data-camera-pose')
  await page.getByRole('button',{name:'Examine',exact:true}).click()
  await page.waitForTimeout(500)
  await expect(page.locator('canvas')).toHaveAttribute('data-camera-transition','moving')
  await expect(page.locator('canvas')).toHaveAttribute('data-camera-transition','settled')
  expect(await page.locator('canvas').getAttribute('data-camera-pose')).not.toBe(overview)
  await page.getByRole('button',{name:'Overview',exact:true}).click()
  await page.waitForTimeout(300)
  await page.getByRole('button',{name:'Examine',exact:true}).click()
  await expect(page.locator('canvas')).toHaveAttribute('data-camera-transition','settled')
  expect(await page.locator('canvas').getAttribute('data-renderer-instance')).toBe(renderer)
  await expect(page.getByRole('combobox',{name:'Graphics quality'})).toHaveCount(0)
  await expect(page.locator('canvas')).toHaveAttribute('data-shadow-policy','static-casters')
  expect(await page.locator('canvas').getAttribute('data-renderer-instance')).toBe(renderer)
})
test('benchmark reduced motion and unavailable WebGL preserve medical access',async({page})=>{
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('/visual-benchmark')
 await expect(page.getByTestId('benchmark-status')).toHaveAttribute('data-state','ready',{timeout:90000})
 await page.getByRole('button',{name:'Examine',exact:true}).click()
 await expect(page.locator('canvas')).toHaveAttribute('data-camera-transition','settled')
 await page.setViewportSize({width:390,height:844})
 await expect(page.getByRole('button',{name:'Overview',exact:true})).toBeInViewport()
 await page.addInitScript(()=>{const old=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=(function(this:HTMLCanvasElement,...args:Parameters<typeof old>){if(String(args[0]).includes('webgl'))return null;return old.apply(this,args)} as typeof old)})
 await page.reload()
 await expect(page.getByText('Spatial view unavailable.',{exact:false})).toBeVisible()
 await expect(page.getByRole('link',{name:'Open accessible medical view'})).toBeVisible()
})
